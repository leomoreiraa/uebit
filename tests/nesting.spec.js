import { test, expect } from '@playwright/test'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'
import JSZip from 'jszip'

async function waitPreview(page) {
  await expect(page.locator('iframe')).toHaveAttribute('data-ready', 'true')
}
async function select(page, id) {
  await page.locator(`[data-tree-id="${id}"]`).click()
}
async function drag(page, id, target, fraction = 0.5) {
  await select(page, id)
  await waitPreview(page)
  const handle = page.locator(`[data-element-id="${id}"] > button`).first()
  await handle.scrollIntoViewIfNeeded()
  const source = await handle.boundingBox()
  const destination = await target.boundingBox()
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2)
  await page.mouse.down()
  await page.mouse.move(destination.x + destination.width / 2, destination.y + destination.height * fraction, { steps: 25 })
  await page.mouse.up()
}

test('pointer sorting moves blocks into empty/nested containers and back out, preserving order', async ({ page }) => {
  await page.goto('/')
  const preview = page.frameLocator('iframe')
  await page.getByRole('button', { name: 'Adicionar container', exact: true }).click()
  const first = await preview.locator('.site > .container').getAttribute('data-block-id')
  await page.getByRole('button', { name: 'Adicionar cabeçalho', exact: true }).click()
  const heading = await preview.locator('h1').getAttribute('data-block-id')
  await page.getByRole('button', { name: 'Selecionar página', exact: true }).click()
  await page.getByRole('button', { name: 'Adicionar container', exact: true }).click()
  const second = await preview.locator('.site > .container').nth(1).getAttribute('data-block-id')
  await drag(page, heading, page.locator(`[data-element-id="${second}"]`))
  await expect(preview.locator(`[data-block-id="${second}"] > h1`)).toHaveCount(1)
  await expect(preview.locator(`[data-block-id="${first}"] > h1`)).toHaveCount(0)
  await select(page, second)
  await page.getByRole('button', { name: 'Adicionar container', exact: true }).click()
  const nested = await preview.locator(`[data-block-id="${second}"] > .container`).getAttribute('data-block-id')
  await drag(page, heading, page.locator(`[data-element-id="${nested}"]`))
  await expect(preview.locator(`[data-block-id="${nested}"] > h1`)).toHaveCount(1)
  await drag(page, nested, page.locator(`[data-element-id="${first}"]`))
  await expect(preview.locator(`[data-block-id="${first}"] > .container > h1`)).toHaveCount(1)
  await drag(page, heading, page.locator('[data-page-end]'))
  await expect(preview.locator('.site > h1:last-child')).toHaveCount(1)
  await drag(page, heading, page.locator(`[data-element-id="${first}"]`), 0.05)
  await expect(preview.locator('.site > h1:first-child')).toHaveCount(1)
  await expect(preview.locator('.site')).toHaveCSS('display', 'flex')
  await expect(preview.locator('.container').first()).toHaveCSS('display', 'flex')
})

test('palette drops enter a nested droppable, and Escape cancels without changing the tree', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Adicionar container', exact: true }).click()
  await page.getByRole('button', { name: 'Adicionar container', exact: true }).click()
  const preview = page.frameLocator('iframe')
  const nested = await preview.locator('.container > .container').getAttribute('data-block-id')
  await waitPreview(page)
  const palette = page.getByRole('button', { name: 'Adicionar parágrafo', exact: true })
  const source = await palette.boundingBox()
  const target = await page.locator(`[data-element-id="${nested}"]`).boundingBox()
  await page.mouse.move(source.x + 30, source.y + 30)
  await page.mouse.down()
  await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 25 })
  await expect(page.locator('[data-drop-preview]')).toBeVisible()
  await page.mouse.up()
  await expect(preview.locator('.container > .container > p')).toHaveCount(1)
  const paragraph = await preview.locator('p').getAttribute('data-block-id')
  await select(page, paragraph)
  const handle = page.locator(`[data-element-id="${paragraph}"] > button`)
  await handle.scrollIntoViewIfNeeded()
  const origin = await handle.boundingBox()
  await page.mouse.move(origin.x + 10, origin.y + 10)
  await page.mouse.down()
  await page.mouse.move(origin.x + 60, origin.y + 60, { steps: 10 })
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await expect(preview.locator('.container > .container > p')).toHaveCount(1)
})

test('friendly flex controls, responsive nesting and subtree removal survive export', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Adicionar container', exact: true }).click()
  const preview = page.frameLocator('iframe')
  const container = await preview.locator('.container').getAttribute('data-block-id')
  await page.getByRole('button', { name: 'Lado a lado', exact: true }).click()
  await page.getByRole('button', { name: 'Centralizar tudo', exact: true }).click()
  await page.getByRole('button', { name: 'Adicionar botão', exact: true }).click()
  await select(page, container)
  await page.getByRole('button', { name: 'Adicionar botão', exact: true }).click()
  await expect(preview.locator('.container')).toHaveCSS('flex-direction', 'row')
  await expect(preview.locator('.container')).toHaveCSS('justify-content', 'center')
  await expect(preview.locator('.container')).toHaveCSS('align-items', 'center')
  const boxes = await preview.locator('.container > button').evaluateAll((nodes) => nodes.map((node) => ({ x: node.getBoundingClientRect().x, y: node.getBoundingClientRect().y })))
  expect(boxes[0].y).toBe(boxes[1].y)
  expect(boxes[0].x).toBeLessThan(boxes[1].x)
  await page.getByRole('button', { name: 'Mobile', exact: true }).click()
  await expect(preview.locator('.container')).toHaveCSS('flex-direction', 'column')
  await select(page, container)
  await page.getByRole('button', { name: 'Bem separados', exact: true }).click()
  await expect(preview.locator('.container')).toHaveCSS('gap', '32px')
  await page.getByRole('button', { name: 'Desktop', exact: true }).click()
  await expect(preview.locator('.container')).toHaveCSS('gap', '16px')
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar Site', exact: true }).click()
  const download = await pending
  const zip = await JSZip.loadAsync(await readFile(await download.path()))
  const css = await zip.file('style.css').async('string')
  expect(css).not.toContain('grid-')
  const folder = testInfo.outputPath('nested-site')
  await mkdir(folder, { recursive: true })
  for (const name of ['index.html', 'style.css', 'script.js']) await writeFile(`${folder}/${name}`, await zip.file(name).async('string'))
  const exported = await page.context().newPage()
  await exported.goto(pathToFileURL(`${folder}/index.html`).href)
  await expect(exported.locator('.container > button')).toHaveCount(2)
  await expect(exported.locator('.container')).toHaveCSS('display', 'flex')
  await exported.setViewportSize({ width: 320, height: 844 })
  await expect(exported.locator('.container')).toHaveCSS('flex-direction', 'column')
  expect(await exported.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Excluir elemento', exact: true }).click()
  await expect(preview.locator('.site > *')).toHaveCount(0)
})

