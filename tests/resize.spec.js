import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import JSZip from 'jszip'

async function dragHandle(page, label, dx, dy, cancel = false) {
  const handle = page.getByRole('button', { name: `Redimensionar: ${label}`, exact: true })
  await handle.scrollIntoViewIfNeeded()
  const box = await handle.boundingBox()
  const scale = await page.locator('[data-device]').evaluate((node) => node.getBoundingClientRect().width / node.offsetWidth)
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + dx * scale, box.y + box.height / 2 + dy * scale, { steps: 15 })
  if (cancel) await page.keyboard.press('Escape')
  await page.mouse.up()
}

test('resize is live, scaled, cancellable and persists for nested desktop/mobile elements', async ({ page }) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/editor')
  await page.getByRole('button', { name: 'Adicionar seção', exact: true }).click()
  await page.getByRole('button', { name: 'Adicionar cabeçalho', exact: true }).click()
  const preview = page.frameLocator('iframe')
  await expect(preview.locator('section h1')).toBeVisible()
  await expect(page.locator('[data-resize-overlay]')).toHaveCount(1)
  const initial = await preview.locator('h1').evaluate((node) => ({ width: node.getBoundingClientRect().width, height: node.getBoundingClientRect().height }))
  const handle = page.getByRole('button', { name: 'Redimensionar: inferior direito', exact: true })
  await handle.scrollIntoViewIfNeeded()
  const box = await handle.boundingBox()
  const scale = await page.locator('[data-device]').evaluate((node) => node.getBoundingClientRect().width / node.offsetWidth)
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 - 180 * scale, box.y + box.height / 2 + 100 * scale, { steps: 15 })
  // The live iframe changes before release, without reloading scripts.
  await expect(preview.locator('h1')).toHaveCSS('width', `${Math.round(initial.width - 180)}px`)
  await expect(preview.locator('h1')).toHaveCSS('height', `${Math.round(initial.height + 100)}px`)
  await page.mouse.up()
  await expect(page.locator('iframe')).toHaveAttribute('data-ready', 'true')
  await expect(preview.locator('h1')).toHaveCSS('width', `${Math.round(initial.width - 180)}px`)
  await dragHandle(page, 'esquerda', 40, 0, true)
  await expect(preview.locator('h1')).toHaveCSS('width', `${Math.round(initial.width - 180)}px`)

  await page.getByRole('button', { name: 'Mobile', exact: true }).click()
  await expect(page.locator('[data-device]')).toHaveAttribute('data-device', 'mobile')
  await expect(preview.locator('h1')).not.toHaveCSS('width', `${Math.round(initial.width - 180)}px`)
  const mobileWidth = await preview.locator('h1').evaluate((node) => node.getBoundingClientRect().width)
  await dragHandle(page, 'direita', -40, 0)
  await expect(preview.locator('h1')).toHaveCSS('width', `${Math.round(mobileWidth - 40)}px`)
  await page.getByRole('button', { name: 'Desktop', exact: true }).click()
  await expect(preview.locator('h1')).toHaveCSS('width', `${Math.round(initial.width - 180)}px`)
  await page.getByRole('button', { name: 'Testar página', exact: true }).click()
  await expect(page.locator('[data-resize-overlay]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Voltar a editar', exact: true }).click()

  const saving = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Salvar Projeto', exact: true }).click()
  const saved = await saving
  const buffer = await readFile(await saved.path())
  await page.reload()
  await page.getByLabel('Arquivo do projeto .frog', { exact: true }).setInputFiles({ name: 'resize.frog', mimeType: 'application/json', buffer })
  await expect(preview.locator('section h1')).toHaveCSS('height', `${Math.round(initial.height + 100)}px`)
  const exporting = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar Site', exact: true }).click()
  const zip = await JSZip.loadAsync(await readFile(await (await exporting).path()))
  const css = await zip.file('style.css').async('string')
  expect(css).toContain(`height: ${Math.round(initial.height + 100)}px`)
  expect(css).toContain(`width: ${Math.round(mobileWidth - 40)}px`)
  expect(errors).toEqual([])
})

test('image can grow past its original height cap and keyboard handles adjust size', async ({ page }) => {
  await page.goto('/editor')
  await page.getByRole('button', { name: 'Adicionar imagem', exact: true }).click()
  const image = page.frameLocator('iframe').locator('img')
  await expect.poll(() => image.evaluate((node) => node.complete && node.naturalWidth > 0)).toBe(true)
  await dragHandle(page, 'inferior', 0, 150)
  await expect(image).toHaveCSS('max-height', 'none')
  await expect.poll(() => image.evaluate((node) => node.getBoundingClientRect().height)).toBeGreaterThan(400)
  const width = await image.evaluate((node) => node.getBoundingClientRect().width)
  await page.getByRole('button', { name: 'Redimensionar: esquerda', exact: true }).focus()
  await page.keyboard.press('Shift+ArrowRight')
  await expect(image).toHaveCSS('width', `${Math.round(width - 10)}px`)
  await page.getByRole('button', { name: 'Altura: Natural', exact: true }).click()
  await expect(image).not.toHaveCSS('height', '550px')
})
