import { test, expect } from '@playwright/test'
import { importCodeProject } from './helpers/project.js'

test('stage hides editing tools, runs actions and returns to the selected block', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Adicionar botão', exact: true }).click()
  await page.getByLabel('Texto do botão', { exact: true }).fill('Minha conquista')
  await page.getByLabel('Ação do botão', { exact: true }).selectOption('message')
  await page.getByLabel('Mensagem do botão', { exact: true }).fill('Funcionou no palco!')
  await page.getByRole('button', { name: 'Aplicar alterações', exact: true }).click()
  await page.getByRole('button', { name: 'Mobile', exact: true }).click()
  await page.getByRole('button', { name: 'Play · Abrir palco', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Palco do seu site' })).toBeVisible()
  await expect(page.getByRole('complementary')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Mover botão', exact: true })).toHaveCount(0)
  await expect(page.locator('#workspace')).toHaveCount(0)
  await expect(page.locator('iframe')).toHaveAttribute('data-ready', 'true')
  await expect.poll(() => page.locator('iframe').evaluate((node) => node.clientWidth)).toBe(390)
  await page.frameLocator('iframe').getByRole('button', { name: 'Minha conquista' }).click()
  await expect(page.frameLocator('iframe').getByRole('status')).toHaveText('Funcionou no palco!')
  await expect(page.getByRole('button', { name: 'Exportar Site', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Voltar ao editor', exact: true }).click()
  await expect(page.getByLabel('Texto do botão', { exact: true })).toHaveValue('Minha conquista')
  await expect(page.getByRole('button', { name: 'Mobile', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

