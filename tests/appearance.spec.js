import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import JSZip from 'jszip'

test('visual properties persist through content edits, mobile sizing, stage and export', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Adicionar cabeçalho', exact: true }).click()
  const heading = page.frameLocator('iframe').getByRole('heading')
  await page.getByRole('button', { name: 'Cor do texto: Azul', exact: true }).click()
  await page.getByRole('button', { name: 'Cor de fundo: Amarelo', exact: true }).click()
  await page.getByRole('button', { name: 'Texto G (36 px)', exact: true }).click()
  await expect(heading).toHaveCSS('color', 'rgb(37, 99, 235)')
  await expect(heading).toHaveCSS('background-color', 'rgb(250, 204, 21)')
  await expect(heading).toHaveCSS('font-size', '36px')
  await page.getByRole('button', { name: 'Largura: Metade', exact: true }).click()
  await page.getByRole('button', { name: 'Altura: Média', exact: true }).click()
  await expect(heading).toHaveCSS('width', '608px')
  await expect(heading).toHaveCSS('min-height', '160px')
  await page.getByLabel('Texto do título', { exact: true }).fill('Meu título colorido')
  await page.getByRole('button', { name: 'Aplicar alterações', exact: true }).click()
  await expect(heading).toHaveText('Meu título colorido')
  await expect(heading).toHaveCSS('color', 'rgb(37, 99, 235)')
  await page.getByRole('button', { name: 'Mobile', exact: true }).click()
  await expect(heading).toHaveCSS('width', '342px')
  await page.getByRole('button', { name: 'Largura: Metade', exact: true }).click()
  await expect(heading).toHaveCSS('width', '163px')
  await page.getByRole('button', { name: 'Desktop', exact: true }).click()
  await expect(heading).toHaveCSS('width', '608px')
  await page.getByRole('button', { name: 'Play · Abrir palco', exact: true }).click()
  await expect(heading).toHaveCSS('background-color', 'rgb(250, 204, 21)')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar Site', exact: true }).click()
  const download = await downloadPromise
  const zip = await JSZip.loadAsync(await readFile(await download.path()))
  const html = await zip.file('index.html').async('string')
  expect(html).toContain('color: rgb(37, 99, 235)')
  expect(html).toContain('background-color: rgb(250, 204, 21)')
  await page.getByRole('button', { name: 'Voltar ao editor', exact: true }).click()
  await page.getByRole('button', { name: 'Cor do texto: Azul', exact: true }).getAttribute('aria-pressed').then((value) => expect(value).toBe('true'))
  await page.getByRole('button', { name: 'Restaurar cor do texto', exact: true }).click()
  await expect(heading).toHaveCSS('color', 'rgb(30, 41, 59)')
  await page.getByRole('button', { name: 'Restaurar cor de fundo', exact: true }).click()
  await expect(heading).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
})
