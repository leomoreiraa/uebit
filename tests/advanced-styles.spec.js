import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import JSZip from 'jszip'

async function field(page, label, value) {
  const input = page.getByLabel(label, { exact: true })
  await input.fill(value)
  await input.press('Enter')
}

test('global and individual styles survive editing, frog reload and site export', async ({ page }) => {
  await page.goto('/editor')
  await page.getByRole('button', { name: 'Adicionar seção', exact: true }).click()
  await page.getByRole('button', { name: 'Adicionar lista', exact: true }).click()
  const preview = page.frameLocator('iframe')
  await expect(preview.locator('section ul li')).toHaveCount(3)
  await field(page, 'Margem superior', '17px')
  await field(page, 'Padding esquerda', '35px')
  await page.getByLabel('Borda inferior · estilo', { exact: true }).selectOption('dashed')
  await field(page, 'Borda inferior · largura', '5px')
  await field(page, 'Borda inferior · cor', '#2563eb')
  await field(page, 'Canto superior esquerdo', '28px')
  await expect(preview.locator('ul')).toHaveCSS('margin-top', '17px')
  await expect(preview.locator('ul')).toHaveCSS('padding-left', '35px')
  await expect(preview.locator('ul')).toHaveCSS('border-bottom', '5px dashed rgb(37, 99, 235)')
  await expect(preview.locator('ul')).toHaveCSS('border-top-left-radius', '28px')
  await field(page, 'Padding direita', '-5px')
  await expect(page.getByLabel('Padding direita', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await field(page, 'Padding direita', '9px')

  await page.getByRole('tab', { name: 'Estilos Globais', exact: true }).click()
  await field(page, 'Fundo global', '#fef3c7')
  await field(page, 'Fonte global', 'Georgia')
  await field(page, 'Padding superior', '11px')
  await expect(preview.locator('body')).toHaveCSS('background-color', 'rgb(254, 243, 199)')
  await expect(preview.locator('body')).toHaveCSS('padding-top', '11px')
  await page.getByLabel('Alvo dos estilos globais').selectOption('*')
  await field(page, 'Cor do texto global', '#15803d')
  await expect(preview.locator('li').first()).toHaveCSS('color', 'rgb(21, 128, 61)')
  await page.getByRole('button', { name: 'Adicionar campo de texto', exact: true }).click()
  await page.getByRole('tab', { name: /^Estilos \d/ }).click()
  await field(page, 'Texto inicial preenchido', 'Ana')
  await page.getByRole('button', { name: 'Aplicar alterações', exact: true }).click()
  await expect(preview.locator('input')).toHaveValue('Ana')

  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Salvar Projeto', exact: true }).click()
  const download = await pending
  const buffer = await readFile(await download.path())
  await page.reload()
  await page.getByLabel('Arquivo do projeto .frog', { exact: true }).setInputFiles({ name: 'aula.frog', mimeType: 'application/json', buffer })
  await expect(page.getByText('Projeto “Meu primeiro site” importado.', { exact: true })).toBeVisible()
  await expect(preview.locator('section ul')).toHaveCSS('padding-left', '35px')
  await expect(preview.locator('body')).toHaveCSS('background-color', 'rgb(254, 243, 199)')
  await expect(page.getByLabel('Texto inicial preenchido', { exact: true })).toHaveValue('Ana')
  const exporting = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar Site', exact: true }).click()
  const zip = await JSZip.loadAsync(await readFile(await (await exporting).path()))
  expect(await zip.file('index.html').async('string')).toContain('<section')
  expect(await zip.file('style.css').async('string')).toContain('UEBIT-GLOBAL:body')
  expect(await zip.file('index.html').async('string')).toContain('padding-left: 35px')
})

test('palette has independent scrolling and stays visible while the canvas scrolls', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 700 })
  await page.goto('/editor')
  const palette = page.getByRole('complementary', { name: 'Paleta de elementos' })
  await expect(palette).toHaveCSS('position', 'sticky')
  await expect(palette).toHaveCSS('overflow-y', 'auto')
  for (let i = 0; i < 8; i++) await page.getByRole('button', { name: 'Adicionar cabeçalho', exact: true }).click()
  await page.evaluate(() => window.scrollTo(0, 500))
  await expect.poll(async () => (await palette.boundingBox()).y).toBeLessThan(20)
  const windowScroll = await page.evaluate(() => window.scrollY)
  await palette.evaluate((node) => { node.scrollTop = 200 })
  expect(await palette.evaluate((node) => node.scrollTop)).toBeGreaterThan(0)
  expect(await page.evaluate(() => window.scrollY)).toBe(windowScroll)
})
